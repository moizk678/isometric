"""Generate tiny contract fixtures. These are not real engineering drawings."""

import argparse
import hashlib
import json
import struct
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIZE = 128
GLYPHS = {
    "2": ("111", "001", "001", "111", "100", "100", "111"),
    "5": ("111", "100", "100", "111", "001", "001", "111"),
    "A": ("010", "101", "101", "111", "101", "101", "101"),
    "E": ("111", "100", "100", "110", "100", "100", "111"),
    "L": ("100", "100", "100", "100", "100", "100", "111"),
    "M": ("101", "111", "111", "101", "101", "101", "101"),
    "V": ("101", "101", "101", "101", "101", "101", "010"),
    " ": ("000",) * 7,
}


def canvas():
    return [[255] * SIZE for _ in range(SIZE)]


def dot(image, x, y, radius=0):
    for yy in range(y - radius, y + radius + 1):
        for xx in range(x - radius, x + radius + 1):
            if (
                0 <= xx < SIZE
                and 0 <= yy < SIZE
                and (xx - x) ** 2 + (yy - y) ** 2 <= radius**2
            ):
                image[yy][xx] = 0


def line(image, x0, y0, x1, y1):
    steps = max(abs(x1 - x0), abs(y1 - y0))
    for step in range(steps + 1):
        x = round(x0 + (x1 - x0) * step / steps)
        y = round(y0 + (y1 - y0) * step / steps)
        dot(image, x, y, 1)


def label(image, text, x, y, scale=3):
    for char in text.upper():
        glyph = GLYPHS[char]
        for row, pattern in enumerate(glyph):
            for col, value in enumerate(pattern):
                if value == "1":
                    for yy in range(scale):
                        for xx in range(scale):
                            dot(image, x + col * scale + xx, y + row * scale + yy)
        x += 4 * scale


def png(image):
    def chunk(kind, payload):
        body = kind + payload
        return (
            struct.pack(">I", len(payload)) + body + struct.pack(">I", zlib.crc32(body))
        )

    rows = b"".join(b"\x00" + bytes(row) for row in image)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 0, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(rows, level=9))
        + chunk(b"IEND", b"")
    )


def drawings():
    connected = canvas()
    line(connected, 16, 64, 112, 64)
    line(connected, 64, 16, 64, 112)
    dot(connected, 64, 64, 4)

    disconnected = canvas()
    line(disconnected, 16, 64, 112, 64)
    line(disconnected, 64, 16, 64, 57)
    line(disconnected, 64, 71, 64, 112)

    note = canvas()
    label(note, "VALVE", 23, 48)

    dimension = canvas()
    line(dimension, 24, 78, 104, 78)
    line(dimension, 24, 70, 24, 86)
    line(dimension, 104, 70, 104, 86)
    label(dimension, "25 MM", 29, 38, 2)

    return {
        "connected_crossing.png": connected,
        "disconnected_crossing.png": disconnected,
        "note_crop.png": note,
        "dimension.png": dimension,
    }


def manifest_entry(name, payload):
    return {
        "drawing_id": name.removesuffix(".png").replace("_", "-"),
        "asset_uri": name,
        "rights_consent": {
            "status": "not_applicable",
            "permission_basis": "generated by this repository",
            "allowed_use": "repository and CI contract tests",
            "recorded_by": "fixture generator",
            "recorded_at": "2026-09-25",
            "deletion_owner": "project owner",
        },
        "source_type": "synthetic",
        "profile": "piping_isometric",
        "difficulty_tags": [name.removesuffix(".png")],
        "split": "development",
        "label_status": "reviewed",
        "annotation_uri": "ground_truth.json",
        "checksum_sha256": hashlib.sha256(payload).hexdigest(),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    payloads = {name: png(image) for name, image in drawings().items()}
    manifest = {
        "schema_version": "1.0.0",
        "entries": [
            manifest_entry(name, payload) for name, payload in payloads.items()
        ],
    }
    outputs = {name: payload for name, payload in payloads.items()}
    outputs["manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    outputs["../../datasets/manifest.template.json"] = (
        json.dumps(
            {"schema_version": "1.0.0", "entries": manifest["entries"][:1]}, indent=2
        )
        + "\n"
    ).encode()
    for name, payload in outputs.items():
        path = HERE / name
        if args.check:
            if not path.exists() or path.read_bytes() != payload:
                raise SystemExit(f"stale synthetic fixture: {path}")
        else:
            path.write_bytes(payload)


if __name__ == "__main__":
    main()
